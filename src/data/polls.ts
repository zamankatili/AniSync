export const generateMorePolls = (count: number) => {
  // Return all unique polls up to count
  if (count <= SEED_POLLS.length) {
    return SEED_POLLS.slice(0, count);
  }
  const result = [...SEED_POLLS];
  while (result.length < count) {
    const item = SEED_POLLS[result.length % SEED_POLLS.length];
    result.push({ ...item, id: `${item.highlight}-${result.length}` } as any);
  }
  return result;
};
